int levenshteinDistance(const string& s1, const string& s2) {
	int m = s1.length(); // k i t t e n : length = 6 : s1[0]=k s1[1]=i s1[2]=t s1[3]=t s1[4]=e s1[5]=n
	int n = s2.length(); // s i t t i n g : length = 7 : s2[0]=s s2[1]=i s2[2]=t s2[3]=t s2[4]=i s2[5]=n s2[6]=g

	vector<vector<int>> dp(m + 1, vector<int>(n + 1, 0));

	for (int i = 0; i <= m; ++i) {
	// 1. 0 <= 6 : true
	// 2. 1 <= 6 : true
	// 3. 2 <= 6 : true
	// 4. 3 <= 6 : true
	// 5. 4 <= 6 : true
	// 6. 5 <= 6 : true
	// 7. 6 <= 6 : true
	// 8. 7 <= 6 : false::break-for
		for (int j = 0; j <= n; ++j) {
		// 1-1. 0 <= 7 : true
		// 1-2. 1 <= 7 : true
		// 1-3. 2 <= 7 : true
		// 1-4. 3 <= 7 : true
		// 1-5. 4 <= 7 : true
		// 1-6. 5 <= 7 : true
		// 1-7. 6 <= 7 : true
		// 1-8. 7 <= 7 : true
		// 1-9. 8 <= 7 : false::break-for
		// 2-1. 0 <= 7 : true
		// 2-2. 1 <= 7 : true
		// 2-3. 2 <= 7 : true
		// 2-4. 3 <= 7 : true
		// 2-5. 4 <= 7 : true
		// 2-6. 5 <= 7 : true
		// 2-7. 6 <= 7 : true
		// 2-8. 7 <= 7 : true
		// 2-9. 8 <= 7 : false::break-for
		// 3-1. 0 <= 7 : true
		// 3-2. 1 <= 7 : true
		// 3-3. 2 <= 7 : true
		// 3-4. 3 <= 7 : true
		// 3-5. 4 <= 7 : true
		// 3-6. 5 <= 7 : true
		// 3-7. 6 <= 7 : true
		// 3-8. 7 <= 7 : true
		// 3-9. 8 <= 7 : false::break-for
		// 4-1. 0 <= 7 : true
		// 4-2. 1 <= 7 : true
		// 4-3. 2 <= 7 : true
		// 4-4. 3 <= 7 : true
		// 4-5. 4 <= 7 : true
		// 4-6. 5 <= 7 : true
		// 4-7. 6 <= 7 : true
		// 4-8. 7 <= 7 : true
		// 4-9. 8 <= 7 : false::break-for
		// 5-1. 0 <= 7 : true
		// 5-2. 1 <= 7 : true
		// 5-3. 2 <= 7 : true
		// 5-4. 3 <= 7 : true
		// 5-5. 4 <= 7 : true
		// 5-6. 5 <= 7 : true
		// 5-7. 6 <= 7 : true
		// 5-8. 7 <= 7 : true
		// 5-9. 8 <= 7 : false::break-for
		// 6-1. 0 <= 7 : true
		// 6-2. 1 <= 7 : true
		// 6-3. 2 <= 7 : true
		// 6-4. 3 <= 7 : true
		// 6-5. 4 <= 7 : true
		// 6-6. 5 <= 7 : true
		// 6-7. 6 <= 7 : true
		// 6-8. 7 <= 7 : true
		// 6-9. 8 <= 7 : false::break-for
		// 7-1. 0 <= 7 : true
		// 7-2. 1 <= 7 : true
		// 7-3. 2 <= 7 : true
		// 7-4. 3 <= 7 : true
		// 7-5. 4 <= 7 : true
		// 7-6. 5 <= 7 : true
		// 7-7. 6 <= 7 : true
		// 7-8. 7 <= 7 : true
		// 7-9. 8 <= 7 : false::break-for
			if (i == 0)
			// 1-1. 0 == 0 : true
			// 1-2. 0 == 0 : true
			// 1-3. 0 == 0 : true
			// 1-4. 0 == 0 : true
			// 1-5. 0 == 0 : true
			// 1-6. 0 == 0 : true
			// 1-7. 0 == 0 : true
			// 1-8. 0 == 0 : true
			// 2-1. 1 == 0 : false
			// 2-2. 1 == 0 : false
			// 2-3. 1 == 0 : false
			// 2-4. 1 == 0 : false
			// 2-5. 1 == 0 : false
			// 2-6. 1 == 0 : false
			// 2-7. 1 == 0 : false
			// 2-8. 7 == 0 : false
			// 3-1. 2 == 0 : false
			// 3-2. 2 == 0 : false
			// 3-3. 2 == 0 : false
			// 3-4. 2 == 0 : false
			// 3-5. 2 == 0 : false
			// 3-6. 2 == 0 : false
			// 3-7. 2 == 0 : false
			// 3-8. 2 == 0 : false
			// 4-1. 2 == 0 : false
			// 4-2. 2 == 0 : false
			// 4-3. 2 == 0 : false
			// 4-4. 2 == 0 : false
			// 4-5. 2 == 0 : false
			// 4-6. 2 == 0 : false
			// 4-7. 2 == 0 : false
			// 4-8. 2 == 0 : false
			// 5-1. 2 == 0 : false
			// 5-2. 2 == 0 : false
			// 5-3. 2 == 0 : false
			// 5-4. 2 == 0 : false
			// 5-5. 2 == 0 : false
			// 5-6. 2 == 0 : false
			// 5-7. 2 == 0 : false
			// 5-8. 2 == 0 : false
			// 6-1. 2 == 0 : false
			// 6-2. 2 == 0 : false
			// 6-3. 2 == 0 : false
			// 6-4. 2 == 0 : false
			// 6-5. 2 == 0 : false
			// 6-6. 2 == 0 : false
			// 6-7. 2 == 0 : false
			// 6-8. 2 == 0 : false
			// 7-1. 2 == 0 : false
			// 7-2. 2 == 0 : false
			// 7-3. 2 == 0 : false
			// 7-4. 2 == 0 : false
			// 7-5. 2 == 0 : false
			// 7-6. 2 == 0 : false
			// 7-7. 2 == 0 : false
			// 7-8. 2 == 0 : false
				dp[i][j] = j;
				// 1-1. dp[0][0] = 0
				// 1-2. dp[0][1] = 1
				// 1-3. dp[0][2] = 2
				// 1-4. dp[0][3] = 3
				// 1-5. dp[0][4] = 4
				// 1-6. dp[0][5] = 5
				// 1-7. dp[0][6] = 6
				// 1-8. dp[0][7] = 7
			else if (j == 0)
			// 2-1. 0 == 0 : true
			// 2-2. 1 == 0 : false
			// 2-3. 2 == 0 : false
			// 2-4. 3 == 0 : false
			// 2-5. 4 == 0 : false
			// 2-6. 5 == 0 : false
			// 2-7. 6 == 0 : false
			// 2-8. 7 == 0 : false
			// 3-1. 0 == 0 : true
			// 3-2. 1 == 0 : false
			// 3-3. 2 == 0 : false
			// 3-4. 3 == 0 : false
				dp[i][j] = i;
				// 2-1. dp[1][0] = 1
				// 3-1. dp[2][0] = 2
			else if (s1[i - 1] == s2[j - 1])
			// 2-2. s1[1 - 1] == s2[1 - 1] : s1[0] == s2[0] : k == s : false
			// 2-3. s1[1 - 1] == s2[2 - 1] : s1[0] == s2[1] : k == i : false
			// 2-4. s1[1 - 1] == s2[3 - 1] : s1[0] == s2[2] : k == t : false
			// 2-5. s1[1 - 1] == s2[4 - 1] : s1[0] == s2[3] : k == t : false
			// 2-6. s1[1 - 1] == s2[5 - 1] : s1[0] == s2[4] : k == i : false
			// 2-7. s1[1 - 1] == s2[6 - 1] : s1[0] == s2[5] : k == n : false
			// 2-8. s1[1 - 1] == s2[7 - 1] : s1[0] == s2[6] : k == g : false
			// 3-2. s1[2 - 1] == s2[1 - 1] : s1[1] == s2[0] : i == s : false
			// 3-3. s1[2 - 1] == s2[2 - 1] : s1[1] == s2[1] : i == i : true
			// 3-4. s1[2 - 1] == s2[3 - 1] : s1[1] == s2[2] : i == t : false
				dp[i][j] = dp[i - 1][j - 1];
				// 3-3. dp[2][2] = dp[2 - 1][2 - 1] : dp[2][2] = dp[1][1] : dp[2][2] = 1
			else
				dp[i][j] = 1 + min({dp[i - 1][j], dp[i][j - 1], dp[i - 1][j - 1]});
				// 2-2. dp[1][1] = 1 + min({dp[1 - 1][1], dp[1][1 - 1], dp[1 - 1][1 - 1]})
				//		dp[1][1] = 1 + min({dp[0][1], dp[1][0], dp[0][0]})
				//		dp[1][1] = 1 + min({1, 1, 0) = 1 + 0 = 1
				//		dp[1][1] = 1
				// 2-3. dp[1][2] = 1 + min({dp[1 - 1][2], dp[1][2 - 1], dp[1 - 1][2 - 1]})
				//		dp[1][2] = 1 + min({dp[0][2], dp[1][1], dp[0][1]})
				//		dp[1][2] = 1 + min({2, 1, 1}) = 1 + 1 = 2
				//		dp[1][2] = 2
				// 2-4. dp[1][3] = 1 + min({dp[1 - 1][3], dp[1][3 - 1], dp[1 - 1][3 - 1]})
				//		dp[1][3] = 1 + min({dp[0][3], dp[1][2], dp[0][2]})
				//		dp[1][3] = 1 + min({3, 2, 2}) = 1 + 2 = 3
				//		dp[1][3] = 3
				// 2-5. dp[1][4] = 1 + min({dp[1 - 1][4], dp[1][4 - 1], dp[1 - 1][4 - 1]})
				//		dp[1][4] = 1 + min({dp[0][4], dp[1][3], dp[0][3]})
				//		dp[1][4] = 1 + min({4, 3, 3}) = 1 + 3 = 4
				//		dp[1][4] = 4
				// 2-6. dp[1][5] = 1 + min({dp[1 - 1][5], dp[1][5 - 1], dp[1 - 1][5 - 1]})
				//		dp[1][5] = 1 + min({dp[0][5], dp[1][4], dp[0][4]})
				//		dp[1][5] = 1 + min({5, 4, 4}) = 1 + 4 = 5
				//		dp[1][5] = 5
				// 2-7. dp[1][6] = 1 + min({dp[1 - 1][6], dp[1][6 - 1], dp[1 - 1][6 - 1]})
				//		dp[1][6] = 1 + min({dp[0][6], dp[1][5], dp[0][5]})
				//		dp[1][6] = 1 + min({6, 5, 5}) = 1 + 5 = 6
				//		dp[1][6] = 6
				// 2-8. dp[1][7] = 1 + min({dp[1 - 1][7], dp[1][7 - 1], dp[1 - 1][7 - 1]})
				//		dp[1][7] = 1 + min({dp[0][7], dp[1][6], dp[0][6]})
				//		dp[1][7] = 1 + min({7, 6, 6}) = 1 + 6 = 7
				//		dp[1][7] = 7
				// 3-2. dp[2][1] = 1 + min({dp[2 - 1][1], dp[2][1 - 1], dp[2 - 1][1 - 1]})
				//		dp[2][1] = 1 + min({dp[1][1], dp[2][0], dp[1][0]})
				//		dp[2][1] = 1 + min({1, 2, 1}) = 1 + 1 = 2
				//		dp[2][1] = 2
				// 3-4. dp[2][3] = 1 + min({dp[2 - 1][3], dp[2][3 - 1], dp[2 - 1][3 - 1]})
				//		dp[2][3] = 1 + min({dp[1][3], dp[2][2], dp[1][2]})
				//		dp[2][3] = 1 + min({3, 1, 2}) = 1 + 1 = 2
				//		dp[2][3] = 2
		}
	}

	return dp[m][n];
}


